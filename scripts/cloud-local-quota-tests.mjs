import assert from 'node:assert/strict';
import {installCloudProfileLocally} from '../src/persistence/cloud-profile.js';
import {readFileSync} from 'node:fs';
const remote={solved:{0:1},badges:{},stars:{},performances:{},daily:{},challenges:{},shards:3,xp:1};
const key='lumenProgressV1';
const local={...remote,solved:{0:1,1:1},xp:10};
const state=new Map([[key,JSON.stringify(local)],['lumenBeforeCloudAuthority_prior','unique old backup']]);
const memory={getItem:k=>state.get(k)??null,setItem:(k,v)=>state.set(k,String(v))};
assert.throws(()=>installCloudProfileLocally(memory,remote),/divergent/);
assert.deepEqual(JSON.parse(state.get(key)),local);
assert.equal(state.get('lumenBeforeCloudAuthority_prior'),'unique old backup');
const quota=new Map([[key,JSON.stringify(remote)]]);
const full={getItem:k=>quota.get(k)??null,setItem:(k,v)=>{if(k.startsWith('lumenBeforeCloudAuthority_')){const e=new Error('Quota exceeded');e.name='QuotaExceededError';e.code=22;throw e}quota.set(k,String(v))}};
assert.equal(installCloudProfileLocally(full,remote),false,'Equal payload needs no write even with full storage');
const improved={...remote,xp:2};
assert.equal(installCloudProfileLocally(full,improved),'memory_only','Verified cloud dominance must not deadlock hydration on quota');
assert.deepEqual(JSON.parse(quota.get(key)),remote,'Original remains intact on failed backup');
const diagnostics=readFileSync(new URL('../src/ui/game-screen.js',import.meta.url),'utf8');
assert.match(diagnostics,/errorName:String\(e\?\.name/);
assert.match(diagnostics,/stage:String\(e\?\.stage/);
assert.match(diagnostics,/kind:e\?\.code==="LOCAL_STORAGE_QUOTA"/);
console.log('Cloud local storage quota and data-loss protections passed');
