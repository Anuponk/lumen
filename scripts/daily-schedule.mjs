// Daily challenge schedule (#882). Append-only: published days never change.
//   node scripts/daily-schedule.mjs --write [--days 371]   extend, keeping existing days
//   node scripts/daily-schedule.mjs --sql                   copy the schedule into the migration block
//   node scripts/daily-schedule.mjs --check                 verify immutability, grids and migration block
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {canonicalQuestList} from '../src/campaign/canonical-quests.js';
import {DAILY_POOL,DAILY_SCHEDULE_START,dailyPool,planDailySchedule,dailyQuest,addDays} from '../src/campaign/daily-challenge.js';

export const SCHEDULE_PATH='content/generated/daily-schedule.json';
export const MIGRATION_PATH='supabase/migrations/20261122090000_daily_challenge_882.sql';
const BEGIN='-- BEGIN DAILY SCHEDULE (generated by scripts/daily-schedule.mjs --sql; append-only)';
const END='-- END DAILY SCHEDULE';
const NL='\n';

export function scheduleSql(days){
 const rows=days.map(e=>"('"+e.day+"','"+e.questId+"',"+e.gridRevision+')');
 return 'insert into lumen_commands.daily_puzzles(day,quest_id,grid_revision) values'+NL+rows.join(','+NL)+NL+'on conflict(day) do nothing;';
}
export function migrationBlock(sql){
 const a=sql.indexOf(BEGIN),b=sql.indexOf(END);
 if(a<0||b<a)throw Error('Missing daily schedule block');
 return sql.slice(a+BEGIN.length,b).split('\r\n').join(NL).trim();
}
export const scheduleHash=value=>createHash('sha256').update('lumen-daily:'+value).digest('hex');
export function buildSchedule({days,existing=[]}){
 const pool=dailyPool(canonicalQuestList());
 const entries=planDailySchedule({pool,start:DAILY_SCHEDULE_START,days,existing,hash:scheduleHash});
 return {schema:'lumen-daily-schedule-v1',start:DAILY_SCHEDULE_START,timeZone:'Europe/Paris',
  pool:{labels:[...DAILY_POOL.labels],minOrdinal:DAILY_POOL.minOrdinal,size:pool.length},days:entries};
}
export function verifySchedule(schedule,{migration=true}={}){
 if(schedule.schema!=='lumen-daily-schedule-v1'||schedule.start!==DAILY_SCHEDULE_START)throw Error('Invalid daily schedule header');
 schedule.days.forEach((e,i)=>{
  if(e.day!==addDays(DAILY_SCHEDULE_START,i))throw Error('Non-contiguous daily schedule at '+e.day);
  const quest=dailyQuest(e);
  if(quest.constellationId!==e.constellationId)throw Error('Constellation mismatch '+e.day);
  if(i&&schedule.days[i-1].constellationId===e.constellationId)throw Error('Same constellation two days running '+e.day);
 });
 if(migration&&migrationBlock(fs.readFileSync(MIGRATION_PATH,'utf8'))!==scheduleSql(schedule.days))throw Error('Migration schedule block differs from '+SCHEDULE_PATH);
 const regenerated=buildSchedule({days:schedule.days.length,existing:schedule.days});
 if(JSON.stringify(regenerated.days)!==JSON.stringify(schedule.days))throw Error('Daily schedule is not reproducible');
 return true;
}

const invoked=(process.argv[1]||'').replace(/\\/g,'/').endsWith('scripts/daily-schedule.mjs');
if(invoked){
 const args=process.argv.slice(2),existing=fs.existsSync(SCHEDULE_PATH)?JSON.parse(fs.readFileSync(SCHEDULE_PATH,'utf8')):null;
 if(args.includes('--sql')){
  if(!existing)throw Error('Missing '+SCHEDULE_PATH);
  const sql=fs.readFileSync(MIGRATION_PATH,'utf8'),a=sql.indexOf(BEGIN),b=sql.indexOf(END),eol=sql.includes('\r\n')?'\r\n':NL;
  if(a<0||b<a)throw Error('Missing daily schedule block');
  fs.writeFileSync(MIGRATION_PATH,sql.slice(0,a+BEGIN.length)+eol+scheduleSql(existing.days).split(NL).join(eol)+eol+sql.slice(b));
  console.log('daily schedule written into '+MIGRATION_PATH);
 }else if(args.includes('--write')){
  const daysArg=args.indexOf('--days'),days=Math.max(daysArg>=0?Number(args[daysArg+1]):371,existing?.days.length||0);
  const schedule=buildSchedule({days,existing:existing?.days||[]});
  if(existing)for(const e of existing.days){const now=schedule.days.find(x=>x.day===e.day);if(JSON.stringify(now)!==JSON.stringify(e))throw Error('Published day changed: '+e.day)}
  verifySchedule(schedule,{migration:false});
  fs.writeFileSync(SCHEDULE_PATH,JSON.stringify(schedule,null,1)+NL);
  console.log('daily schedule: '+schedule.days.length+' days from '+schedule.start+', pool '+schedule.pool.size);
 }else{
  if(!existing)throw Error('Missing '+SCHEDULE_PATH);
  verifySchedule(existing);
  console.log('daily schedule check: '+existing.days.length+' days, reproducible, every grid resolvable, migration block identical');
 }
}
