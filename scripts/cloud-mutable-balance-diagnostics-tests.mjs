assert.match(game,/fields:Array\.isArray\(resolution\.fields\)\?resolution\.fields:\[\]/);
assert.doesNotMatch(game,/recordCloudDiagnostic\("hydration_reconciliation",\{[^\n]*(?:local\.shards|cloud\.xp)/);
