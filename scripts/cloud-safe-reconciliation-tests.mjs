import assert from 'node:assert/strict';
import {reconcileDominantLocalProfile,sameCloudProfile} from '../src/persistence/cloud-profile.js';
const base={solved:{0:1},badges:{},shards:3,xp:0,skyScore:0,daily:{},challenges:{}};
const local={...structuredClone(base),solved:{0:1,1:1}};
const m=new Map([['lumenProgressV1',JSON.stringify(local)]]);
const storage={getItem:k=>m.get(k)??null,setItem:(k,v)=>m.set(k,String(v))};
let server=structuredClone(base),writes=0;
const api={async rpc(method,args){if(method==='lumen_cas_profile'){if(!sameCloudProfile(server,args.p_expected))return {data:false,error:null};server=structuredClone(args.p_payload);writes++;return {data:true,error:null}}if(method==='lumen_restore_profile')return {data:structuredClone(server),error:null};throw Error(method)}};
const resolved=await reconcileDominantLocalProfile(api,storage,base);
assert.equal(resolved.status,'reconciled');assert.equal(writes,1);assert.equal(server.solved[1],1);
assert([...m.keys()].some(k=>k.startsWith('lumenBeforeCloudReconcileLocal_')));
assert([...m.keys()].some(k=>k.startsWith('lumenBeforeCloudReconcileRemote_')));
const changedBalance={...base,shards:9};
m.set('lumenProgressV1',JSON.stringify(changedBalance));server=structuredClone(base);
assert.deepEqual(await reconcileDominantLocalProfile(api,storage,base),{status:'blocked',reason:'mutable_balance'});
assert.equal(writes,1);assert.equal(m.get('lumenProgressV1'),JSON.stringify(changedBalance));
const missingRemote={...base,solved:{0:1,2:1}};
assert.equal((await reconcileDominantLocalProfile(api,storage,missingRemote)).status,'blocked');
console.log('Reconciliation blocks currency conflicts, preserves two verified backups and CAS-protects writes');
