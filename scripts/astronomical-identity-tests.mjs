import assert from "node:assert/strict";
import {astronomicalIdentityAudit,IAU_BY_RESERVED_CONSTELLATION} from "./astronomical-identity-audit.mjs";
const audit=astronomicalIdentityAudit();
assert.equal(audit.quests,500);
assert.equal(audit.adventures,5);
assert.equal(audit.canonicalConstellations,50);
assert.equal(audit.registeredConstellations,50);
assert.equal(audit.unregistered.length,0);
assert.deepEqual(audit.unknown,[]);
assert.deepEqual(audit.repeated,[]);
assert.equal(audit.mapped.length,50);
assert.equal(audit.reserved.length,0);
assert.deepEqual(audit.unregistered,[]);
assert.deepEqual(audit.mapped.filter(c=>c.id in IAU_BY_RESERVED_CONSTELLATION).map(c=>c.iau).sort(),["Del","Equ","Her","Lep","Mon","Oph"]);
assert(audit.mapped.filter(c=>c.id in IAU_BY_RESERVED_CONSTELLATION).every(c=>c.questCount===10 && c.packId==="real-adventure-03"));
assert.equal(audit.mapped.find(x=>x.label==="Orion")?.iau,"Ori");
assert.equal(audit.mapped.find(x=>x.id==="iau-cmi")?.iau,"CMi");
assert.equal(audit.mapped.find(x=>x.id==="iau-cvn")?.iau,"CVn");
console.log("Astronomical identity audit:",JSON.stringify({registered:audit.registeredConstellations,planned:audit.canonicalConstellations,unregistered:audit.unregistered}));
