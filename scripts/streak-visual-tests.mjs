import assert from 'node:assert/strict';
import fs from 'node:fs';
import {streakVisual,lostStreak} from '../src/campaign/streak-visual.js';
const dates={'2026-10-08':1,'2026-10-09':1,'2026-10-10':1,'2026-10-11':1};
const grace=streakVisual(dates,'2026-10-13');
assert.equal(grace.streak,4);
assert.equal(grace.protectedDay,true);
assert.equal(grace.slots.length,8);
assert.deepEqual(grace.slots.map(s=>s.kind),['lit','lit','lit','lit','missed','future','future','future']);
assert.equal(grace.focus,5,'Circle the next star, not the missed star');
assert.equal(lostStreak(dates,'2026-10-13'),null,'One missed day remains protected');
assert.deepEqual(lostStreak(dates,'2026-10-14'),{last:'2026-10-11',prior:4,gap:3});
assert.equal(lostStreak({},'2026-10-14'),null,'New players never see loss animation');
assert.equal(streakVisual({'2026-10-13':1},'2026-10-13').slots.length,7);
const screen=fs.readFileSync(new URL('../src/ui/game-screen.js',import.meta.url),'utf8');
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
assert.match(screen,/function maybeShowStreakLoss/);
assert.match(screen,/authSessionPending\|\|\(lumenUser&&!cloudProfileReady\)/);
assert.match(screen,/lumenStreakLossShownV1:/);
assert.match(html,/id="streakLossModal"/);
assert.match(html,/id="dailyProtection"/);
console.log('Protected streak and one-time loss display contracts passed');
