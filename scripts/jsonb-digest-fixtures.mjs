// Prints SQL for disposable PostgreSQL: the client jsonb text/digest must equal
// PostgreSQL's own jsonb output for tricky values and a full 880-quest profile.
// Never connects to a database.
import { jsonbText, jsonbDigest } from '../src/persistence/jsonb-digest.js';
import { canonicalQuestList } from '../src/campaign/canonical-quests.js';
import { applyQuestVictory } from '../src/campaign/quest-victory.js';

const facts = { seconds: 70, assistanceUsed: false, hintUsed: false, mistakeCommitted: false, qualifying: true, challengeFailed: false, qualifiedDay: '2026-11-06', qualifiedAt: '2026-11-06T12:00:00.000Z' };
const complete = { catalogueOrigin: 4, solved: {}, canonicalQuestState: {}, performances: {}, badges: {}, stars: {}, challenges: {}, xp: 0, shards: 0 };
for (const quest of canonicalQuestList()) applyQuestVictory(complete, quest, facts);

export const SAMPLES = [
  { name: 'empty', value: {} },
  { name: 'key order by byte length then bytes', value: { bb: 1, a: 2, ab: 3, b: 4, é: 5, z: 6, '10': 7, '9': 8, aaa: { y: [], x: {} } } },
  { name: 'strings and escapes', value: { s: 'quote " back \\ slash / tab \t nl \n cr \r ff \f bs \b ctl \u0001 \u001f del \u007f é 漢字 😀  ' } },
  { name: 'numbers', value: { n: [0, -1, 1.5, 0.1, 0.30000000000000004, 1e21, 1.2e21, 1e-7, 1.5e-7, -2.5e-8, 123456789012, 9007199254740991] } },
  { name: 'nested arrays and nulls', value: { a: [null, true, false, [1, [2, []]], { k: null }], 'é': 'x' } },
  { name: 'full 880-quest profile', value: complete },
];

const literal = (value) => "'" + JSON.stringify(value).replaceAll("'", "''") + "'::jsonb";
const lines = ['-- Generated by scripts/jsonb-digest-fixtures.mjs; disposable PostgreSQL only.', 'do $$', 'begin'];
for (const { name, value } of SAMPLES) {
  const text = jsonbText(value),
    digest = await jsonbDigest(value);
  if (text.length < 4000) lines.push(` assert (${literal(value)})::text=${"'" + text.replaceAll("'", "''") + "'"},${"'" + ('jsonb text: ' + name).replaceAll("'", "''") + "'"};`);
  lines.push(` assert encode(sha256(convert_to((${literal(value)})::text,'UTF8')),'hex')='${digest}',${"'" + ('digest: ' + name).replaceAll("'", "''") + "'"};`);
}
lines.push('end $$;');
console.log(lines.join('\n'));
