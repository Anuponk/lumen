alter table lumen.feedback add column if not exists user_id uuid;
alter table lumen.feedback add column if not exists anonymous_id text;
alter table lumen.feedback add column if not exists kind text;
alter table lumen.feedback add column if not exists message text;
alter table lumen.feedback add column if not exists puzzle_id integer;
alter table lumen.feedback add column if not exists board_state jsonb;
alter table lumen.feedback add column if not exists elapsed_seconds integer;
alter table lumen.feedback add column if not exists hints_used integer not null default 0;
