-- Real PostgreSQL execution with synthetic session claims, not a live Auth test.
-- Every test write is rolled back. This file can only name QA objects.
begin;
set local role lumen_recette_runner;
do $$
declare uid uuid:=gen_random_uuid();other_uid uuid:=gen_random_uuid();cid uuid:=gen_random_uuid();
 seed jsonb;raw text;manifest jsonb;r jsonb;receipt jsonb;before_profile jsonb;latest jsonb;facts jsonb;q text;legacy_q text;day text:=(now() at time zone 'Europe/Paris')::date::text;
begin
 assert current_user='lumen_recette_runner';
 assert not has_schema_privilege(current_user,'lumen','usage');
 assert not has_schema_privilege(current_user,'lumen_commands','usage');
 assert not has_schema_privilege(current_user,'auth','usage');
 begin execute 'select payload from lumen.profile_snapshots limit 0';raise exception 'production read allowed';exception when insufficient_privilege then null;end;
 insert into lumen_recette.actors(id) values(uid),(other_uid);
 perform set_config('request.jwt.claim.sub',uid::text,true);
 seed:='{"solved":{"0":1,"1":1,"2":1,"3":1,"4":1,"5":1},"badges":{},"shards":3,"xp":90,"future":{"keep":"étoile"}}';
 raw:=seed::text;
 manifest:=jsonb_build_object('version',1,'userId',uid,'claimId',cid,'policy','new-profile-net-balance-v1','sourceRaw',raw,'seedRaw',raw,'sourceDigest',encode(sha256(convert_to(raw,'UTF8')),'hex'),'seedDigest',encode(sha256(convert_to(raw,'UTF8')),'hex'));
 assert lumen_recette.lumen_guest_claim_version()=0;
 begin perform lumen_recette.lumen_claim_guest_profile(uid,manifest);raise exception 'inactive writer accepted';exception when sqlstate '55000' then null;end;
 insert into lumen_recette.sync_release_approvals values(repeat('a',40),1,repeat('b',64),now());
 perform lumen_recette.set_sync_cohort(uid,'shadow',repeat('a',40),repeat('b',64));
 begin perform lumen_recette.set_sync_cohort(uid,'active',repeat('a',40),repeat('b',64));raise exception 'paused activation accepted';exception when sqlstate '55000' then null;end;
 update lumen_recette.sync_rollout_control set allow_new_activations=true;
 perform lumen_recette.set_sync_cohort(uid,'active',repeat('a',40),repeat('b',64));
 update lumen_recette.sync_rollout_control set allow_new_activations=false;
 perform lumen_recette.set_sync_cohort(uid,'active',repeat('a',40),repeat('b',64));
 assert (select count(*) from lumen_recette.sync_cohort_events where user_id=uid)=2;
 assert lumen_recette.lumen_guest_claim_version()=1;
 r:=lumen_recette.lumen_claim_guest_profile(uid,manifest);
 assert r->>'status'='initialized';
 assert lumen_recette.lumen_claim_guest_profile(uid,manifest)=r;
 assert lumen_recette.lumen_get_guest_claim(uid,cid)=r;
 assert (select count(*) from lumen_recette.guest_claim_receipts where user_id=uid)=1;
 assert lumen_recette.lumen_restore_profile(uid)=seed;
 begin perform lumen_recette.lumen_claim_guest_profile(other_uid,manifest);raise exception 'foreign claim allowed';exception when insufficient_privilege then null;end;
 begin perform lumen_recette.lumen_claim_guest_profile(uid,manifest||'{"seedDigest":"wrong"}');raise exception 'changed claim accepted';exception when invalid_parameter_value then null;end;
 assert lumen_recette.lumen_claim_guest_profile(uid,manifest||jsonb_build_object('claimId',gen_random_uuid()))->>'status'='review_required';
 perform lumen_recette.lumen_commit_wallet_command('wallet-establish-v1',uid,'{"kind":"establish"}');
 r:=lumen_recette.lumen_commit_wallet_command('attempt-reset-0-hint-1',uid,'{"kind":"hint","attemptId":"attempt","resetCount":0,"sequence":1}');
 assert r->>'balance'='2';
 perform lumen_recette.lumen_commit_wallet_command('attempt-reset-0-hint-1',uid,'{"kind":"hint","attemptId":"attempt","resetCount":0,"sequence":1}');
 assert lumen_recette.lumen_get_wallet_command('attempt-reset-0-hint-1',uid)->>'balance'='2';
 assert (select count(*) from lumen_recette.wallet_receipts where user_id=uid and operation_id='attempt-reset-0-hint-1')=1;
 latest:=lumen_recette.lumen_restore_profile(uid);
 assert latest->>'shards'='2';assert latest->'future'=seed->'future';
 begin perform lumen_recette.lumen_cas_profile(latest,jsonb_set(latest,'{shards}','3'),uid);raise exception 'old snapshot cancelled spend';exception when invalid_parameter_value then null;end;
