 assert (select count(*) from lumen_recette.canonical_receipts where user_id=uid)=1;
 begin perform lumen_recette.lumen_commit_quest_command('recette-q07-reset-0',uid,q,facts||'{"seconds":20}');raise exception 'immutable facts changed';exception when invalid_parameter_value then null;end;
 before_profile:=latest;
 r:=lumen_recette.lumen_commit_quest_command('recette-q07-reset-1',uid,q,facts||'{"seconds":20,"assistanceUsed":true,"hintUsed":true}');
 latest:=lumen_recette.lumen_restore_profile(uid);
 assert r->'outcome'->>'firstCompletion'='false';
 assert latest->'xp'=before_profile->'xp';
 assert latest->'canonicalQuestState'->q->'badges'->>'mastery'='false','runs cannot manufacture Mastery';
 begin perform lumen_recette.lumen_get_quest_command('recette-q07-reset-0',other_uid);raise exception 'foreign receipt read';exception when insufficient_privilege then null;end;
 -- A second context/session sees exactly the same confirmed account projection.
 perform set_config('request.jwt.claim.sub',other_uid::text,true);
 assert lumen_recette.lumen_restore_profile(other_uid) is null;
 perform set_config('request.jwt.claim.sub',uid::text,true);
 assert lumen_recette.lumen_restore_profile(uid)=latest;
 assert (latest::text)::jsonb=latest,'export round-trip preserves unknown fields';
 assert lumen_recette.lumen_sync_contract(uid)->>'stage'='active';
