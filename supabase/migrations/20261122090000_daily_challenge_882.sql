-- The single rank source: general = completed runs of participating ranking
-- members; friends = me + accepted friends who participate. Ties share a rank.
create or replace function lumen_commands.daily_ranks(p_day date,p_user uuid)
returns table(general_rank integer,general_total integer,friends_rank integer,friends_total integer)
language sql stable security definer set search_path='' as $$
 with done as (
  select r.user_id,r.score,coalesce(m.participating,false) as participating
  from lumen_commands.daily_runs r left join lumen_commands.ranking_members m on m.user_id=r.user_id
  where r.day=p_day and r.status='completed'
 ), mine as (select score from done where user_id=p_user),
 general as (select * from done where participating),
 friends as (select d.* from done d where d.user_id=p_user or (d.participating and exists(
  select 1 from lumen.social_friend_edges e where e.user_id=p_user and e.friend_user_id=d.user_id and e.state='friends')))
 select
  case when exists(select 1 from general where user_id=p_user) then 1+(select count(*) from general g,mine where g.score<mine.score)::integer end,
  (select count(*) from general)::integer,
  case when exists(select 1 from mine) then 1+(select count(*) from friends f,mine where f.score<mine.score)::integer end,
  (select count(*) from friends)::integer
$$;

-- Freeze ranks once nobody can still finish (close + 6 h). Idempotent.
create or replace function lumen_commands.daily_finalize(p_day date) returns boolean
language plpgsql security definer set search_path='' as $$
begin
 if clock_timestamp()<lumen_commands.daily_closes_at(p_day)+interval '6 hours' then return false;end if;
 if exists(select 1 from lumen_commands.daily_finalized where day=p_day) then return true;end if;
 perform pg_advisory_xact_lock(hashtextextended('lumen-daily-finalize:'||p_day::text,0));
 if exists(select 1 from lumen_commands.daily_finalized where day=p_day) then return true;end if;
 update lumen_commands.daily_runs set status='abandoned',finished_at=coalesce(finished_at,clock_timestamp()) where day=p_day and status='started';
 insert into lumen_commands.daily_standings(user_id,day,general_rank,general_total,friends_rank,friends_total)
  select r.user_id,p_day,x.general_rank,x.general_total,x.friends_rank,x.friends_total
  from lumen_commands.daily_runs r cross join lateral lumen_commands.daily_ranks(p_day,r.user_id) x
  where r.day=p_day and r.status='completed'
  on conflict(user_id,day) do nothing;
 insert into lumen_commands.daily_finalized(day) values(p_day) on conflict do nothing;
 return true;
end $$;

create or replace function lumen_commands.daily_run_json(r lumen_commands.daily_runs) returns jsonb
language sql stable set search_path='' as $$
 select case when r.user_id is null then null else jsonb_build_object('day',r.day,'operation_id',r.operation_id,'quest_id',r.quest_id,'grid_revision',r.grid_revision,
  'status',r.status,'started_at',r.started_at,'finished_at',r.finished_at,'seconds',r.seconds,'score',r.score,
  'penalty',case when r.score is not null then r.score-r.seconds end,
  'finish_deadline',r.started_at+interval '6 hours') end
$$;

