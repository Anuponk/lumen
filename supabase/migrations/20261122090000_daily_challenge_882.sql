-- #882 (EPIC #881 Lot 3, PR A): daily challenge engine and server contracts.
-- Additive and idempotent; disabled by default (feature flag daily_challenge).
-- One official ranked attempt per account and Europe/Paris civil day; both
-- rankings (general and friends) read the same result row. No campaign,
-- wallet, badge, record, entitlement or #638 podium data is written.
-- See docs/DAILY_CHALLENGE.md. Rollback: docs/DAILY_CHALLENGE.md §7.
begin;

create table if not exists lumen_commands.daily_puzzles(
 day date primary key,
 quest_id text not null references lumen_commands.quest_rules(quest_id),
 grid_revision integer not null check(grid_revision>=0),
 source text not null default 'schedule' check(source in ('schedule','override')),
 published_at timestamptz not null default now()
);
create table if not exists lumen_commands.daily_runs(
 user_id uuid not null references auth.users(id) on delete cascade,
 day date not null references lumen_commands.daily_puzzles(day),
 operation_id text not null check(operation_id ~ '^[A-Za-z0-9._-]{1,120}$'),
 quest_id text not null,
 grid_revision integer not null,
 started_at timestamptz not null default clock_timestamp(),
 status text not null default 'started' check(status in ('started','completed','abandoned')),
 seconds integer check(seconds between 0 and 86400),
 hint integer check(hint between 0 and 10000),
 verify integer check(verify between 0 and 10000),
 guided integer check(guided between 0 and 10000),
 score integer check(score>=0),
 finished_at timestamptz,
 primary key(user_id,day),
 check((status='completed')=(score is not null))
);
create index if not exists daily_runs_board_idx on lumen_commands.daily_runs(day,score) where status='completed';
create table if not exists lumen_commands.daily_standings(
 user_id uuid not null references auth.users(id) on delete cascade,
 day date not null,
 general_rank integer check(general_rank>=1),
 general_total integer not null check(general_total>=0),
 friends_rank integer check(friends_rank>=1),
 friends_total integer not null check(friends_total>=0),
 finalized_at timestamptz not null default now(),
 primary key(user_id,day)
);
create table if not exists lumen_commands.daily_finalized(day date primary key,finalized_at timestamptz not null default now());
alter table lumen_commands.daily_puzzles enable row level security;
alter table lumen_commands.daily_runs enable row level security;
alter table lumen_commands.daily_standings enable row level security;
alter table lumen_commands.daily_finalized enable row level security;
revoke all on lumen_commands.daily_puzzles,lumen_commands.daily_runs,lumen_commands.daily_standings,lumen_commands.daily_finalized from public,anon,authenticated,service_role;

