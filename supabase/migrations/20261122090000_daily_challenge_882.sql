-- Begin or resume THE official attempt of today (reload, other device,
-- concurrent calls: same row, same server start). Online only by design.
create or replace function public.lumen_daily_begin(p_operation_id text) returns jsonb
language plpgsql security definer set search_path='' as $$
declare me uuid:=lumen_commands.daily_caller();d date:=lumen_commands.daily_today();p lumen_commands.daily_puzzles%rowtype;r lumen_commands.daily_runs%rowtype;
begin
 if p_operation_id is null or p_operation_id !~ '^[A-Za-z0-9._-]{1,120}$' then raise exception using errcode='22023',message='invalid_operation';end if;
 select * into p from lumen_commands.daily_puzzles where day=d;
 if not found then raise exception using errcode='22023',message='daily_unavailable';end if;
 -- Same automatic ranking membership policy as #638 (opt-out respected).
 perform lumen_commands.ranking_auto(clock_timestamp());
 perform pg_advisory_xact_lock(hashtextextended('lumen-daily:'||me::text,0));
 insert into lumen_commands.daily_runs(user_id,day,operation_id,quest_id,grid_revision) values(me,d,p_operation_id,p.quest_id,p.grid_revision)
  on conflict(user_id,day) do nothing;
 select * into r from lumen_commands.daily_runs where user_id=me and day=d;
 return lumen_commands.daily_run_json(r)||jsonb_build_object('server_now',clock_timestamp(),'closes_at',lumen_commands.daily_closes_at(d),'resumed',r.operation_id<>p_operation_id or r.started_at<clock_timestamp()-interval '2 seconds');
end $$;

-- Finish once. The duration is bounded by the server start; the score uses
-- the official #638 formula. A repeated or late call never changes a result.
create or replace function public.lumen_daily_finish(p_day date,p_operation_id text,p_status text,p_seconds integer,p_hint integer,p_verify integer,p_guided integer)
returns jsonb language plpgsql security definer set search_path='' as $$
declare me uuid:=auth.uid();r lumen_commands.daily_runs%rowtype;facts jsonb;s integer;
begin
 if me is null then raise exception using errcode='42501',message='account_required';end if;
 if p_status not in ('completed','abandoned') then raise exception using errcode='22023',message='invalid_status';end if;
 if coalesce(p_hint,-1) not between 0 and 10000 or coalesce(p_verify,-1) not between 0 and 10000 or coalesce(p_guided,-1) not between 0 and 10000
  or coalesce(p_seconds,-1) not between 0 and 86400 then raise exception using errcode='22023',message='invalid_counts';end if;
 perform pg_advisory_xact_lock(hashtextextended('lumen-daily:'||me::text,0));
 select * into r from lumen_commands.daily_runs where user_id=me and day=p_day for update;
 if not found then raise exception using errcode='22023',message='run_not_found';end if;
 if r.operation_id<>p_operation_id then raise exception using errcode='22023',message='operation_mismatch';end if;
 if r.status<>'started' then return lumen_commands.daily_run_json(r)||jsonb_build_object('replayed',true);end if;
 if clock_timestamp()>r.started_at+interval '6 hours' then
  update lumen_commands.daily_runs set status='abandoned',finished_at=clock_timestamp() where user_id=me and day=p_day returning * into r;
  return lumen_commands.daily_run_json(r)||jsonb_build_object('expired',true);
 end if;
 if p_status='abandoned' then
  update lumen_commands.daily_runs set status='abandoned',finished_at=clock_timestamp() where user_id=me and day=p_day returning * into r;
  return lumen_commands.daily_run_json(r);
 end if;
 if p_seconds>extract(epoch from clock_timestamp()-r.started_at)+5 then raise exception using errcode='22023',message='invalid_duration';end if;
 facts:=jsonb_build_object('seconds',p_seconds,'hintUsed',p_hint>0,'assistanceUsed',p_hint+p_verify+p_guided>0,
  'timing',jsonb_build_object('version',1,'gridRevision',r.grid_revision,'helpUses',jsonb_build_object('hint',p_hint,'verify',p_verify,'guided',p_guided)));
 s:=lumen_commands.official_time(facts,r.grid_revision);
 update lumen_commands.daily_runs set status='completed',seconds=p_seconds,hint=p_hint,verify=p_verify,guided=p_guided,score=s,finished_at=clock_timestamp()
  where user_id=me and day=p_day returning * into r;
 return lumen_commands.daily_run_json(r);
end $$;

-- Both rankings from the same rows: top 3 (ties share a rank) + my position,
-- real participant counts, public nicknames and official times only.
create or replace function public.lumen_daily_board(p_day date default null) returns jsonb
language plpgsql security definer set search_path='' as $$
declare me uuid:=lumen_commands.daily_caller();d date:=coalesce(p_day,lumen_commands.daily_today());is_final boolean;
 mine lumen_commands.daily_runs%rowtype;st lumen_commands.daily_standings%rowtype;gr integer;gt integer;fr integer;ft integer;g jsonb;f jsonb;
begin
 if d>lumen_commands.daily_today() then raise exception using errcode='22023',message='daily_not_open';end if;
 is_final:=lumen_commands.daily_finalize(d);
 select * into mine from lumen_commands.daily_runs x where x.user_id=me and x.day=d;
 select x.general_rank,x.general_total,x.friends_rank,x.friends_total into gr,gt,fr,ft from lumen_commands.daily_ranks(d,me) x;
 if is_final then
  select * into st from lumen_commands.daily_standings x where x.user_id=me and x.day=d;
  if st.user_id is not null then gr:=st.general_rank;gt:=st.general_total;fr:=st.friends_rank;ft:=st.friends_total;end if;
 end if;
 with done as (
  select r.user_id,r.score,btrim(p.nickname) as nickname,coalesce(m.participating,false) as participating,r.user_id=me as is_me
  from lumen_commands.daily_runs r join lumen.profiles p on p.user_id=r.user_id and p.nickname_ready
  left join lumen_commands.ranking_members m on m.user_id=r.user_id
  where r.day=d and r.status='completed'
 ), gen as (select *,rank() over(order by score) as place,row_number() over(order by score,nickname collate "C") as pos from done where participating),
 fri as (select *,rank() over(order by score) as place,row_number() over(order by score,nickname collate "C") as pos from done x where x.is_me or (x.participating and exists(
  select 1 from lumen.social_friend_edges e where e.user_id=me and e.friend_user_id=x.user_id and e.state='friends')))
 select coalesce((select jsonb_agg(jsonb_build_object('nickname',nickname,'score',score,'rank',place,'mine',is_me) order by pos) from gen where pos<=3),'[]'),
        coalesce((select jsonb_agg(jsonb_build_object('nickname',nickname,'score',score,'rank',place,'mine',is_me) order by pos) from fri where pos<=3),'[]')
  into g,f;
 return jsonb_build_object('day',d,'final',is_final,'closes_at',lumen_commands.daily_closes_at(d),
  'my_run',lumen_commands.daily_run_json(mine),
  'general',jsonb_build_object('participants',gt,'top',g,'me',case when mine.status='completed' then jsonb_build_object('rank',gr,'score',mine.score) end),
  'friends',jsonb_build_object('participants',ft,'top',f,'me',case when mine.status='completed' then jsonb_build_object('rank',fr,'score',mine.score) end));
end $$;

-- "Ta semaine dans les étoiles": Monday→Sunday (Europe/Paris) containing
-- p_day. Missed days carry no penalty; ranks are frozen once finalized.
create or replace function public.lumen_daily_week(p_day date default null) returns jsonb
language plpgsql security definer set search_path='' as $$
declare me uuid:=lumen_commands.daily_caller();today date:=lumen_commands.daily_today();anchor date:=coalesce(p_day,lumen_commands.daily_today());
 monday date;d date;days_json jsonb:='[]';r lumen_commands.daily_runs%rowtype;st lumen_commands.daily_standings%rowtype;
 is_final boolean;gr integer;gt integer;fr integer;ft integer;
begin
 if anchor>today then raise exception using errcode='22023',message='daily_not_open';end if;
 monday:=anchor-(extract(isodow from anchor)::integer-1);
 for i in 0..6 loop
  d:=monday+i;
  if d>today then days_json:=days_json||jsonb_build_array(jsonb_build_object('day',d,'state','future'));continue;end if;
  is_final:=lumen_commands.daily_finalize(d);
  r:=null;st:=null;
  select * into r from lumen_commands.daily_runs x where x.user_id=me and x.day=d;
  if r.user_id is null then days_json:=days_json||jsonb_build_array(jsonb_build_object('day',d,'state','missed','final',is_final));continue;end if;
  if r.status<>'completed' then days_json:=days_json||jsonb_build_array(jsonb_build_object('day',d,'state',r.status,'final',is_final,'run',lumen_commands.daily_run_json(r)));continue;end if;
  if is_final then select * into st from lumen_commands.daily_standings x where x.user_id=me and x.day=d;end if;
  if st.user_id is not null then gr:=st.general_rank;gt:=st.general_total;fr:=st.friends_rank;ft:=st.friends_total;
  else select x.general_rank,x.general_total,x.friends_rank,x.friends_total into gr,gt,fr,ft from lumen_commands.daily_ranks(d,me) x;end if;
  days_json:=days_json||jsonb_build_array(jsonb_build_object('day',d,'state','completed','final',st.user_id is not null,'run',lumen_commands.daily_run_json(r),
   'general_rank',gr,'general_total',gt,'friends_rank',fr,'friends_total',ft));
 end loop;
 return jsonb_build_object('monday',monday,'days',days_json);
end $$;

