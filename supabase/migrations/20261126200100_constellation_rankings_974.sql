create or replace function lumen_commands.ranking_points(p_place integer)
returns integer language sql immutable set search_path='' as $$
 select case when p_place is null or p_place < 1 then 0
  when p_place = 1 then 100 when p_place = 2 then 80 when p_place = 3 then 65
  when p_place = 4 then 55 when p_place = 5 then 50
  else greatest(10, 50 - 2 * (p_place - 5)) end;
$$;
