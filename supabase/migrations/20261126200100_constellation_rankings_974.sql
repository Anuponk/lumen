-- #974: constellation and adventure rankings (owner scale validated 24/11/2026).
-- Points per ranked quest from its official place (same qualifying scores, same
-- visibility as lumen_ranking_board, echoes excluded): 1st 100, 2nd 80, 3rd 65,
-- 4th 55, 5th 50, then -2 per place down to a floor of 10. Ties share place and
-- points. Unplayed quest: 0. Constellation = sum of its quests, adventure = sum of
-- its constellations (= its quests).
--
-- Free-first: materialized and incremental. When a score (or a player's
-- visibility, or a quest's grid revision) changes, only THAT quest's places are
-- recomputed and only the affected players' totals for its constellation and
-- adventure are re-summed (at most 10 / one adventure of quests per player). A
-- read never recomputes: top 3 + my position by index, pages on demand.
-- Totals are re-summed from per-quest points (never decremented in place), so a
-- player who leaves a ranking only has rows deleted (erasure guards stay happy).
--
-- Additive: three derived tables, one source-owned grouping table (seeded by
-- scripts/ranking-groups-fixtures.mjs), triggers and two read RPCs. Historical
-- scores are only read. Rollback: drop the triggers, functions and the four
-- tables (derived data only), restore lumen_privacy.policy_before_rankings_974.
begin;
set local lock_timeout = '5s';

create table if not exists lumen_commands.ranking_groups (
 quest_id text primary key check (quest_id ~ '^[A-Za-z0-9._-]{1,120}$'),
 constellation_id text not null check (constellation_id ~ '^[A-Za-z0-9._-]{1,120}$'),
 adventure_id text not null check (adventure_id ~ '^[A-Za-z0-9._-]{1,120}$')
);
create index if not exists ranking_groups_constellation on lumen_commands.ranking_groups(constellation_id);
create index if not exists ranking_groups_adventure on lumen_commands.ranking_groups(adventure_id);

create table if not exists lumen_commands.ranking_quest_points (
 quest_id text not null,
 user_id uuid not null references auth.users(id) on delete cascade,
 place integer not null check (place >= 1),
 points integer not null check (points between 10 and 100),
 primary key (quest_id, user_id)
);
create index if not exists ranking_quest_points_user on lumen_commands.ranking_quest_points(user_id, quest_id);

create table if not exists lumen_commands.ranking_constellation_totals (
 constellation_id text not null,
 user_id uuid not null references auth.users(id) on delete cascade,
 points integer not null check (points > 0),
 quests integer not null check (quests > 0),
 updated_at timestamptz not null default now(),
 primary key (constellation_id, user_id)
);
create index if not exists ranking_constellation_order on lumen_commands.ranking_constellation_totals(constellation_id, points desc, user_id);
create index if not exists ranking_constellation_user on lumen_commands.ranking_constellation_totals(user_id);

create table if not exists lumen_commands.ranking_adventure_totals (
 adventure_id text not null,
 user_id uuid not null references auth.users(id) on delete cascade,
 points integer not null check (points > 0),
 quests integer not null check (quests > 0),
 updated_at timestamptz not null default now(),
 primary key (adventure_id, user_id)
);
create index if not exists ranking_adventure_order on lumen_commands.ranking_adventure_totals(adventure_id, points desc, user_id);
create index if not exists ranking_adventure_user on lumen_commands.ranking_adventure_totals(user_id);

alter table lumen_commands.ranking_groups enable row level security;
alter table lumen_commands.ranking_quest_points enable row level security;
alter table lumen_commands.ranking_constellation_totals enable row level security;
alter table lumen_commands.ranking_adventure_totals enable row level security;
revoke all on lumen_commands.ranking_groups, lumen_commands.ranking_quest_points,
 lumen_commands.ranking_constellation_totals, lumen_commands.ranking_adventure_totals from public, anon, authenticated;

