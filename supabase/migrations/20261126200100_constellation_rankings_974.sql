-- Re-sum one constellation and one adventure for the given players only.
create or replace function lumen_commands.ranking_retotal(p_constellation text, p_adventure text, p_users uuid[])
returns void language plpgsql security definer set search_path='' as $$
begin
 if p_users is null or cardinality(p_users) = 0 then return; end if;
 delete from lumen_commands.ranking_constellation_totals t
  where t.constellation_id = p_constellation and t.user_id = any(p_users)
    and not exists (select 1 from lumen_commands.ranking_quest_points q join lumen_commands.ranking_groups g using (quest_id)
                     where q.user_id = t.user_id and g.constellation_id = p_constellation);
 insert into lumen_commands.ranking_constellation_totals as t (constellation_id, user_id, points, quests)
 select p_constellation, q.user_id, sum(q.points)::integer, count(*)::integer
   from lumen_commands.ranking_quest_points q join lumen_commands.ranking_groups g using (quest_id)
  where g.constellation_id = p_constellation and q.user_id = any(p_users)
  group by q.user_id order by q.user_id
 on conflict (constellation_id, user_id) do update set points = excluded.points, quests = excluded.quests, updated_at = now()
  where (t.points, t.quests) is distinct from (excluded.points, excluded.quests);
 delete from lumen_commands.ranking_adventure_totals t
  where t.adventure_id = p_adventure and t.user_id = any(p_users)
    and not exists (select 1 from lumen_commands.ranking_quest_points q join lumen_commands.ranking_groups g using (quest_id)
                     where q.user_id = t.user_id and g.adventure_id = p_adventure);
 insert into lumen_commands.ranking_adventure_totals as t (adventure_id, user_id, points, quests)
 select p_adventure, q.user_id, sum(q.points)::integer, count(*)::integer
   from lumen_commands.ranking_quest_points q join lumen_commands.ranking_groups g using (quest_id)
  where g.adventure_id = p_adventure and q.user_id = any(p_users)
  group by q.user_id order by q.user_id
 on conflict (adventure_id, user_id) do update set points = excluded.points, quests = excluded.quests, updated_at = now()
  where (t.points, t.quests) is distinct from (excluded.points, excluded.quests);
end $$;
revoke all on function lumen_commands.ranking_retotal(text, text, uuid[]) from public, anon, authenticated;

-- Recompute the places of ONE quest (current grid revision, visible players) and
-- propagate only the differences. Serialized per quest; returns affected players.
create or replace function lumen_commands.ranking_refresh_quest(p_quest_id text)
returns integer language plpgsql security definer set search_path='' as $$
declare g lumen_commands.ranking_groups; v_revision integer; v_fresh jsonb; v_affected uuid[];
begin
 if p_quest_id is null then return 0; end if;
 perform pg_advisory_xact_lock(hashtextextended('lumen-ranking-quest:' || p_quest_id, 0));
 select * into g from lumen_commands.ranking_groups where quest_id = p_quest_id;
 if not found then return 0; end if;
 select grid_revision into v_revision from lumen_commands.quest_rules where quest_id = p_quest_id;
 if not found then return 0; end if;
 -- Same population as lumen_commands.ranking_board (echoes are never scored).
 select coalesce(jsonb_agg(jsonb_build_object('u', r.user_id, 'p', r.place, 'pt', lumen_commands.ranking_points(r.place))), '[]'::jsonb)
   into v_fresh
   from (select s.user_id, rank() over (order by s.score)::integer as place
           from lumen_commands.ranking_scores s
           join lumen_commands.ranking_members m using (user_id)
           join lumen.profiles p using (user_id)
          where s.quest_id = p_quest_id and s.grid_revision = v_revision
            and m.participating and p.nickname_ready and not p.ranking_opted_out) r;
 select array_agg(distinct coalesce(n.u, o.user_id) order by coalesce(n.u, o.user_id)) into v_affected
   from jsonb_to_recordset(v_fresh) as n(u uuid, p integer, pt integer)
   full join (select user_id, place, points from lumen_commands.ranking_quest_points where quest_id = p_quest_id) o on o.user_id = n.u
  where n.u is null or o.user_id is null or n.p <> o.place or n.pt <> o.points;
 if v_affected is null then return 0; end if;
 delete from lumen_commands.ranking_quest_points q
  where q.quest_id = p_quest_id and q.user_id = any(v_affected)
    and not exists (select 1 from jsonb_to_recordset(v_fresh) as n(u uuid, p integer, pt integer) where n.u = q.user_id);
 insert into lumen_commands.ranking_quest_points (quest_id, user_id, place, points)
 select p_quest_id, n.u, n.p, n.pt from jsonb_to_recordset(v_fresh) as n(u uuid, p integer, pt integer)
  where n.u = any(v_affected) order by n.u
 on conflict (quest_id, user_id) do update set place = excluded.place, points = excluded.points;
 perform lumen_commands.ranking_retotal(g.constellation_id, g.adventure_id, v_affected);
 return cardinality(v_affected);
end $$;
revoke all on function lumen_commands.ranking_refresh_quest(text) from public, anon, authenticated;

create or replace function lumen_commands.ranking_refresh_user(p_user uuid)
returns integer language plpgsql security definer set search_path='' as $$
declare q text; n integer := 0;
begin
 for q in select distinct s.quest_id from lumen_commands.ranking_scores s where s.user_id = p_user
          union select r.quest_id from lumen_commands.ranking_quest_points r where r.user_id = p_user
          order by 1 loop
  n := n + lumen_commands.ranking_refresh_quest(q);
 end loop;
 return n;
end $$;
revoke all on function lumen_commands.ranking_refresh_user(uuid) from public, anon, authenticated;

-- Triggers: statement level for scores (one refresh per touched quest), row level
-- for the rare visibility and grid-revision changes.
create or replace function lumen_commands.ranking_scores_changed()
returns trigger language plpgsql security definer set search_path='' as $$
declare q text;
begin
 if tg_op = 'INSERT' then
  for q in select distinct quest_id from new_rows order by 1 loop perform lumen_commands.ranking_refresh_quest(q); end loop;
 elsif tg_op = 'DELETE' then
  for q in select distinct quest_id from old_rows order by 1 loop perform lumen_commands.ranking_refresh_quest(q); end loop;
 else
  for q in select quest_id from new_rows union select quest_id from old_rows order by 1 loop perform lumen_commands.ranking_refresh_quest(q); end loop;
 end if;
 return null;
end $$;
